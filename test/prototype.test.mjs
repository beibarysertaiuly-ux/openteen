import { test, beforeEach } from 'node:test'
import assert from 'node:assert/strict'

const memory = new Map()
globalThis.localStorage = { getItem: k => memory.get(k) ?? null,
  setItem: (k, v) => memory.set(k, v), removeItem: k => memory.delete(k) }
const { default: store } = await import('../src/store/useStore.js')
const { correctInterest, moderateMessage, findSharedInterests } = await import('../src/utils/mockData.js')
const state = () => store.getState()
beforeEach(() => state().startDemo())

test('demo starts with fictional profiles, a sample conversation, and no self-matching', () => {
  assert.equal(state().currentUser.id, 'demo-alex')
  assert.equal(state().matches[0].id, 'demo-sam')
  assert.equal(state().messages['demo-sam'].length, 2)
  assert.deepEqual(state().getSwipeUsers().map(u => u.id), ['demo-jamie', 'demo-robin'])
  assert.ok(state().allUsers.every(u => u.isFictional && !('password' in u) && !('email' in u)))
})
test('recipient must accept; duplicates and self-requests do not create friendships', () => {
  const jamie = state().allUsers.find(u => u.id === 'demo-jamie')
  state().addFriendRequest({ id: 'r1', user: jamie })
  state().addFriendRequest({ id: 'r2', user: jamie })
  state().addFriendRequest({ id: 'self', user: state().currentUser })
  assert.equal(state().allFriendRequests.length, 1)
  assert.equal(state().acceptFriendRequest('r1'), null)
  state().switchDemoUser('demo-jamie')
  assert.equal(state().friendRequests.length, 1)
  assert.equal(state().acceptFriendRequest('r1').id, 'demo-alex')
  assert.equal(state().acceptFriendRequest('r1'), null)
  state().switchDemoUser('demo-alex')
  assert.ok(state().matches.some(u => u.id === 'demo-jamie'))
})
test('messages are shared by both participants with the correct perspective', () => {
  state().addMessage('demo-sam', { id: 'new', text: 'A new message', sender: 'me', reactions: [] })
  state().switchDemoUser('demo-sam')
  assert.equal(state().messages['demo-alex'].at(-1).text, 'A new message')
  assert.equal(state().messages['demo-alex'].at(-1).sender, 'them')
  state().addMessage('demo-alex', { id: 'reply', text: 'A reply', sender: 'me', reactions: [] })
  state().switchDemoUser('demo-alex')
  assert.equal(state().messages['demo-sam'].at(-1).sender, 'them')
  state().addMessage('demo-robin', { id: 'unmatched', text: 'No delivery' })
  assert.ok(!state().messages['demo-robin'])
})
test('reactions persist for both participants', () => {
  const messages = structuredClone(state().messages)
  messages['demo-sam'][0].reactions = ['👍']
  state().setMessages(messages)
  state().switchDemoUser('demo-sam')
  assert.deepEqual(state().messages['demo-alex'][0].reactions, ['👍'])
})
test('blocking removes both sides of chat and prevents further delivery', () => {
  state().blockUser('demo-sam')
  assert.equal(state().matches.length, 0)
  assert.equal(state().blockedUsersData[0].name, 'Sam')
  state().switchDemoUser('demo-sam')
  assert.equal(state().matches.length, 0)
  assert.ok(!state().getSwipeUsers().some(u => u.id === 'demo-alex'))
  state().addMessage('demo-alex', { id: 'blocked', text: 'No delivery' })
  state().switchDemoUser('demo-alex')
  state().unblockUser('demo-sam')
  assert.equal(state().messages['demo-sam'].length, 2)
})
test('preferences and reports stay with the active account', () => {
  state().setAiGrammarAssist(true)
  state().setShowInSwipe(false)
  state().reportUser('demo-robin', 'Local report')
  state().switchDemoUser('demo-jamie')
  assert.equal(state().aiGrammarAssist, false)
  assert.equal(state().reportedUsers.length, 0)
  assert.ok(!state().getSwipeUsers().some(u => u.id === 'demo-alex'))
  state().switchDemoUser('demo-alex')
  assert.equal(state().aiGrammarAssist, true)
  assert.equal(state().reportedUsers.length, 1)
})
test('profile edits propagate to discovery without exposing local credentials', () => {
  state().setUser({ ...state().currentUser, displayName: 'New name', password: 'disposable' })
  state().switchDemoUser('demo-robin')
  const alex = state().getSwipeUsers().find(u => u.id === 'demo-alex')
  assert.equal(alex.name, 'New name')
  assert.ok(!('password' in alex))
})
test('conversation data and account settings survive storage rehydration', async () => {
  state().setAiGrammarAssist(true)
  state().addMessage('demo-sam', { id: 'persist', text: 'Remember this', reactions: [] })
  const saved = localStorage.getItem('openteen-prototype-v2')
  store.setState({ conversations: {}, messages: {}, aiGrammarAssist: false })
  localStorage.setItem('openteen-prototype-v2', saved)
  await store.persist.rehydrate()
  assert.equal(state().messages['demo-sam'].at(-1).text, 'Remember this')
  assert.equal(state().aiGrammarAssist, true)
})
test('interest normalization and phrase filtering are deterministic rules', () => {
  assert.equal(correctInterest(' Soccer '), 'football')
  assert.deepEqual(findSharedInterests({ interests: ['music', 'art'] }, { interests: ['music'] }), ['music'])
  assert.equal(moderateMessage('Hello, what music do you like?').isSafe, true)
  assert.equal(moderateMessage('What is your address?').isSafe, false)
})
